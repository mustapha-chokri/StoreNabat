export function t(
  locale: string,
  key: string,
  overrides?: Record<string, string>
): string {
  if (overrides && overrides[key]) return overrides[key];
  const lang = locale === 'fr' ? 'fr' : locale === 'en' ? 'en' : 'ar';
  return BUILTIN_DICTIONARIES[lang][key] || BUILTIN_DICTIONARIES.en[key] || key;
}

export function pickI18n(
  map: I18nMap | null | undefined,
  locale: string,
  fallback = ''
): string {
  if (!map) return fallback;
  return map[locale] || map.ar || map.fr || map.en || Object.values(map)[0] || fallback;
}

export function formatMoney(
  amount: number | string,
  locale: string,
  currencySymbols: Record<string, string> = { ar: 'د.م.', fr: 'DH', en: 'MAD' },
  position: 'before' | 'after' = 'after'
): string {
  const num = Number(amount || 0).toFixed(2).replace(/\.00$/, '');
  const sym = currencySymbols[locale] || currencySymbols.ar || 'MAD';
  return position === 'before' ? `${sym} ${num}` : `${num} ${sym}`;
}

